/*
  Hand-maintained table of Tailwind v4 utility *families* — which class prefixes exist
  and what kind of value scale they pull from. Tailwind's utility engine (which prefixes
  exist, what they expand to) is compiled into the `tailwindcss` package's JS/WASM build
  rather than published as a declarative data file (its `utilities.css` is just
  `@tailwind utilities;`), so this table is authored against the Tailwind docs utilities
  reference (https://tailwindcss.com/docs/) and needs to be updated by hand when Tailwind
  adds/renames utilities. The actual scale VALUES it pulls from (colors, spacing, font
  sizes, ...) come from Scripts/data/theme.generated.js, which IS auto-generated — see
  gen/generate-theme.mjs.

  This is a broad, representative set covering the utilities developers reach for daily.
  It does not enumerate every single niche utility in the docs (e.g. individual mask-*
  gradient utilities, font-variant-numeric keywords, table/caption utilities) — add more
  entries below following the same shape as needed.

  Entry shapes:
    { kind: 'static', category, items: [{ label, css }] }
      Exact class names with no generated value suffix.

    { kind: 'scale', category, prefixes: [{ prefix, props }], scale: <name in theme data>,
      extraKeywords?: [{ suffix, value }], negative?: bool, valueFormat?: (raw) => cssValue }
      Expands to `${prefix}-${key}` for every key in the named theme scale, plus any
      `extraKeywords` as literal suffixes (e.g. `p-px`, `w-full`).

    { kind: 'color', category, prefixes: [{ prefix, props }], extraKeywords?: string[] }
      Expands to `${prefix}-${colorKey}` for every color in the generated palette, with a
      Color swatch. `extraKeywords` are appended as plain (non-swatch) keyword classes
      (e.g. `inherit`, `current`, `transparent`).

    { kind: 'numericList', category, prefixes: [{ prefix, props }], values: string[],
      unit?: string, negative?: bool }
      Expands to `${prefix}-${n}` for each value in `values`, formatting the CSS value as
      `${n}${unit}`.
*/

