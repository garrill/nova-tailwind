/*
  Hand-authored, human-facing text for the Tailwind reference sidebar (Scripts/sidebar-data.js),
  keyed by the `id` field on each Scripts/data/utilities.js family object. Kept separate from
  utilities.js (which stays structural/mechanical, easy to diff against Tailwind's docs) —
  this file is prose only, no nova.* dependency, and can be extended independently as more
  families are added.

  FAMILY_NAMES: a short display name for the family's tree node (utilities.js has no free-text
  name today — deriving one programmatically from a multi-prefix array isn't reliable).
  FAMILY_DOCS: a one-sentence description of what the family does, shown as a tooltip.

  PROPERTY_DOC_SLUGS / PREFIX_DOC_SLUG_OVERRIDES: power the sidebar's "Open in Tailwind Docs"
  right-click command (Scripts/sidebar-data.js#resolveDocSlug) — see that function for how
  they're combined. tailwindcss.com/docs/ is (almost entirely) one page per real CSS property,
  using the property name itself as the URL slug, which is what PROPERTY_DOC_SLUGS maps —
  verified against the docs site's own nav (https://tailwindcss.com/docs). A handful of
  `utilities.js` families describe their `props` with non-CSS descriptive text instead of a real
  property (e.g. `'filter: blur(...)'`, `'box-shadow ring width'`, `'scale (x)'`) because that
  text is also what gets shown as completion/hover detail — PREFIX_DOC_SLUG_OVERRIDES hand-maps
  just those `${family.id}::${prefix}` pairs directly to a slug, keyed by family id rather than
  prefix alone since the same prefix name (e.g. `shadow`, `text-shadow`) is reused by unrelated
  families (box-shadow's own scale vs. shadow-color's color prefix).
*/

