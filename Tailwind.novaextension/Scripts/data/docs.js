/*
  Docs-site data for the Tailwind reference sidebar (Scripts/sidebar-data.js). Kept separate
  from utilities.js (which stays structural/mechanical, easy to diff against Tailwind's docs) —
  no nova.* dependency.

  DOC_SECTIONS: tailwindcss.com/docs's own utility navigation, transcribed in order — each
  section (Layout, Flexbox & Grid, …) and its pages, one per CSS property. The sidebar groups
  every class under the page that documents it (Section → page → class), so this is the
  official grouping rather than one invented here. `title` is the nav's own label, given only
  where it isn't the slug itself (the filter sub-pages are prefixed with their parent, since
  `blur` appears under both filter and backdrop-filter); `description` is the page's own
  one-line summary (its <meta name="description">), shown as the page node's tooltip. Pages
  this extension has no classes for (e.g. `zoom`) are listed anyway and simply don't appear in
  the sidebar — keeping the table a straight copy of the nav makes it easy to re-check.

  PROPERTY_DOC_SLUGS / PREFIX_DOC_SLUG_OVERRIDES: power the sidebar's "Open in Tailwind Docs"
  right-click command (Scripts/sidebar-data.js#resolveDocSlug) — see that function for how
  they're combined. tailwindcss.com/docs/ is (almost entirely) one page per real CSS property,
  using the property name itself as the URL slug, which is what PROPERTY_DOC_SLUGS maps —
  verified against the docs site's own nav (https://tailwindcss.com/docs). A handful of
  `utilities.js` families describe their `props` with non-CSS descriptive text instead of a real
  property (e.g. `'filter: blur(...)'`, `'box-shadow ring width'`, `'scale (x)'`) because that
  text is also what gets shown as completion/hover detail — PREFIX_DOC_SLUG_OVERRIDES hand-maps
  just those `${family.id}::${prefix}` pairs directly to a slug, keyed by family id rather than
  prefix alone since the same prefix name (e.g. `shadow`, `text-shadow`) is reused by unrelated
  families (box-shadow's own scale vs. shadow-color's color prefix).
*/

